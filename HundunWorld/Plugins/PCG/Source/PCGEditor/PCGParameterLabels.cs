        /// <summary>把一个英文名（槽位名或枚举选项）换成中文标签；表里没有就原样返回。</summary>
        public static string Label(string english)
        {
            if (string.IsNullOrEmpty(english))
                return english;

            return Zh.TryGetValue(english, out string chinese) ? chinese : english;
        }

        /// <summary>表里有没有这个名字（离屏断言用它钉覆盖率）。</summary>
        public static bool Has(string english) => !string.IsNullOrEmpty(english) && Zh.ContainsKey(english);

        /// <summary>表里登记了多少条，供断言报数。</summary>
        public static int Count => Zh.Count;
