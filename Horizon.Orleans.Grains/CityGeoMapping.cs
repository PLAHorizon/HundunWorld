        public static (double Lat, double Lng)? GetCoordinates(string cityName)
        {
            if (string.IsNullOrEmpty(cityName)) return null;
            return _cityCoords.TryGetValue(cityName, out var coords) ? coords : null;
        }

        public static string ExtractCityName(string location)
        {
            if (string.IsNullOrEmpty(location)) return "";
            foreach (var city in _cityCoords.Keys)
            {
                if (location.Contains(city)) return city;
            }
            return location;
        }
